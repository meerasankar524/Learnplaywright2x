// ============================================================
// 96 - What is a Function?
// ============================================================
// A function is like a mini-recipe. You write it once, then you can use it
// over and over again whenever you need it.
// 
// Think of it like a "juice machine" - you turn it on, and it does its job.
// ============================================================

// STEP 1: DEFINE (Create) the function
// We use the keyword "function", give it a name, and put the code inside {}
function sayHello() {
    console.log("Hello! How are you?");
}

// STEP 2: CALL (Run) the function
// To use the function, just write its name followed by ()
sayHello();

// You can call it as many times as you want!
sayHello();
sayHello();

// Output:
// Hello! How are you?
// Hello! How are you?
// Hello! How are you?
