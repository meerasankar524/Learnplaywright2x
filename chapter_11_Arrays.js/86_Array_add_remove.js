let arr = [1, 2, 3];
console.log(arr);

//ADD to END PUSH
arr.push(4);
console.log(arr);

// POP Remove from END

arr.pop(4);
console.log(arr);

//add multiple values
arr.push(5, 6);
console.log(arr);

// Add at Beginning
arr.unshift(8);
console.log(arr);

// Remove from Beginning
arr.shift(0);
console.log(arr);